"""Regenerate checked-in C# catalogue from explicit public paths. Requires Pillow.
Run from any directory: python tools/update-mobile-artwork.py [--check]
No directory discovery, network requests, or runtime image inspection.
"""
import hashlib
import json
from pathlib import Path
import sys
from PIL import Image

root = Path(__file__).resolve().parent.parent
image_root = root / 'webapp/WebApplication/Images'
allowed = {'about', 'background', 'company', 'home', 'iching', 'membership',
           'ninestar', 'astrology', 'numerology', 'ui', 'shared', 'flags'}
lines = []
keys = set()
paths = set()
# Canonical filenames first; retain published mobile IDs as aliases.
legacy_ids = {"ui/constitution.png": "ui.solar-nature",
              "ui/character.png": "ui.lunar-nature"}
for path in (root / 'tools/mobile-artwork-paths.txt').read_text().splitlines():
    if not path or path.startswith('#'):
        continue
    relative = Path(path)
    if relative.is_absolute() or '..' in relative.parts or relative.parts[0] not in allowed:
        raise ValueError('Non-public path: ' + path)
    if path in paths:
        raise ValueError('Duplicate path: ' + path)
    paths.add(path)
    full = image_root / relative
    with Image.open(full) as image:
        width, height = image.size
        mime = Image.MIME[image.format]
    stem = relative.stem + ('-animated' if relative.suffix.lower() == '.gif' else '')
    variant = 'dark' if stem.endswith('-dark') else 'default'
    stem = stem[:-5] if variant == 'dark' else stem
    group = relative.parent.as_posix().replace('/', '.')
    artwork_id = group + '.' + stem.lower()
    if (artwork_id, variant) in keys:
        raise ValueError('Duplicate ID/variant: ' + artwork_id)
    keys.add((artwork_id, variant))
    revision = hashlib.sha256(full.read_bytes()).hexdigest()
    args = [artwork_id, group, variant, path, revision, mime]
    lines.append('            new ArtworkSource(' + ', '.join(json.dumps(v) for v in args)
                 + ', ' + str(width) + ', ' + str(height) + '),')
    if path in legacy_ids:
        alias = legacy_ids[path]
        if (alias, variant) in keys:
            raise ValueError('Duplicate alias: ' + alias)
        keys.add((alias, variant))
        args[0] = alias
        lines.append('            new ArtworkSource(' + ', '.join(json.dumps(v) for v in args)
                     + ', ' + str(width) + ', ' + str(height) + '),')
output = '''// Generated by tools/update-mobile-artwork.py. Edit the explicit allowlist, then regenerate.
namespace K9.WebApplication.Helpers
{
    public static partial class MobileArtworkRegistry
    {
        private static readonly ArtworkSource[] Sources =
        {
''' + '\n'.join(lines) + '''
        };
    }
}
'''
target = root / 'webapp/WebApplication/Helpers/MobileArtworkRegistry.Data.cs'
if '--check' in sys.argv:
    if target.read_text() != output:
        raise SystemExit('Artwork metadata is stale; regenerate it.')
else:
    target.write_text(output)
print('Artwork metadata: ' + str(len(paths)) + ' files, ' + str(len({k[0] for k in keys})) + ' IDs.')
